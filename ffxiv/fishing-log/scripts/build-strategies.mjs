import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),require=createRequire(import.meta.url);
const read=name=>JSON.parse(fs.readFileSync(path.join(root,name),'utf8'));
const refs=read('guides/references.json'),notes=require('../guides/notes.cjs'),context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'data.js'),'utf8'),context);
const data=context.window.FISHING_DATA,byId=new Map([...Object.values(data.related),...data.fishes].map(f=>[f.id,f]));
if(data.revisions.teamcraft!==refs.catalogRevision)throw Error('Catalog changed: recheck guide coverage and conditions before building.');
const scope=data.fishes.filter(f=>f.big&&!f.stars),fish={};
for(const f of scope){
  if(!refs.fish[f.id])throw Error('Missing source audit: '+f.id);
  const note=notes[f.id];
  for(const match of JSON.stringify(note||{}).matchAll(/\{(\d+)\}/g))if(!byId.has(+match[1]))throw Error('Unknown reference: '+match[1]);
  for(const slap of note?.slaps||[])for(const id of slap.ids){
    if(id===f.id||!byId.get(id)?.routes?.some(r=>f.routes.some(t=>r.spotKey===t.spotKey)))throw Error(`Invalid slap target ${f.id} → ${id}`);
  }
  fish[f.id]={...refs.fish[f.id],...(note?{note}:{}),reviewed:!!note};
}
if(Object.keys(notes).some(id=>!fish[id]))throw Error('Strategy outside catalog scope.');
// Ku'er shares Ruby Dragon's preparation chapter; it is not a separate chapter.
fish[24214].guide=fish[24993].guide;fish[24214].volume=4;fish[24214].sharedWith=24993;
const skills=read('../fisher-skills/official.json');
const output={schemaVersion:1,checked:refs.checked,patch:refs.patch,catalogRevision:refs.catalogRevision,sources:refs.sources,
  coverage:{total:scope.length,legendary:scope.filter(f=>f.legendary).length,reviewed:Object.values(fish).filter(f=>f.reviewed).length,linked:Object.values(fish).filter(f=>f.guide).length},
  skills:Object.fromEntries(skills.map(s=>[s.name,{level:s.level,anchor:s.anchor}])),fish};
fs.writeFileSync(path.join(root,'strategy-data.js'),'// Generated by scripts/build-strategies.mjs. See guides/README.md.\nwindow.FISHING_STRATEGIES='+JSON.stringify(output)+';\n');
console.log(output.coverage);
