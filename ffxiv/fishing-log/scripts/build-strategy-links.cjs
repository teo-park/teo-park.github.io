const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'data.js'),'utf8'),context);
const data=context.window.FISHING_DATA,engine=require('../engine.js').create(data);
const content=require('../../fisher-skills/big-fish/content.cjs'),review=require('../strategy-review.json');
const types=content.types.map((t,i)=>({number:i+1,id:t.id,title:t.title}));
const eligible=data.fishes.filter(f=>f.kind==='rod'&&f.big&&!f.stars),fish={};
for(const entry of [...review.loops,...review.rareIntuition]){
  if(!eligible.some(f=>f.id===entry.id)||!/^https:\/\//.test(entry.source))throw Error('Invalid reviewed fish: '+entry.id);
}
for(const loop of review.loops)if(!['target','preparation'].includes(loop.stage)||!engine.byId.get(loop.bait)?.fish)throw Error('Invalid reviewed loop: '+loop.id);
for(const f of eligible){
  const paths=f.routes.flatMap(r=>engine.paths(r));
  if(!paths.length||paths.some(p=>!p.complete))throw Error('Review incomplete bait path: '+f.id);
  const stages=Math.max(...paths.map(p=>p.ids.length-1));
  const main=stages===0?[1]:stages>1?[4]:[],preparation=[],methods=stages===1?[2,3]:[];
  const predators=f.routes.flatMap(r=>r.predators||[]);
  if(predators.length)preparation.push(predators.some(p=>engine.byId.get(p.id)?.big)?7:6);
  if(review.rareIntuition.some(r=>r.id===f.id)&&!preparation.includes(7))preparation.push(7);
  for(const loop of review.loops.filter(r=>r.id===f.id)){
    const group=loop.stage==='target'?main:preparation;
    if(loop.stage==='target'&&!paths.some(p=>p.ids.includes(loop.bait)))throw Error('Reviewed loop no longer on path: '+f.id);
    if(!group.includes(5))group.push(5);
  }
  fish[f.id]={main,preparation,methods};
}
const result={checked:review.checked,dataUpdatedAt:data.updatedAt,types,fish};
fs.writeFileSync(path.join(root,'strategy-links-data.js'),'/* Generated by scripts/build-strategy-links.cjs. */\nwindow.FISHING_STRATEGY_LINKS='+JSON.stringify(result)+';\n');
console.log(`Built strategy links for ${eligible.length} big fish.`);
